from typing import List
from pydantic import BaseModel, Field, field_validator
from langchain_core.prompts import PromptTemplate


from dotenv import load_dotenv
import os

load_dotenv()

api_key = os.getenv('GOOGLE_API_KEY')

from langchain_google_genai import ChatGoogleGenerativeAI
llm_low = ChatGoogleGenerativeAI(model='gemini-2.0-flash', temperature=0.0)
llm_mid = ChatGoogleGenerativeAI(model='gemini-2.0-flash', temperature=0.5)
llm_high = ChatGoogleGenerativeAI(model='gemini-2.0-flash', temperature=1.0)


class RandomText(BaseModel):
    """Structured output for LLM generating random text"""
    random_text: str = Field(description="A random piece of text generated by the LLM")
    
def generate_random_text(llm):
    prompt = PromptTemplate.from_template("Generate a random piece of text, which is longer than 100 words and lesss than 300 words.")
    structured_llm = llm.with_structured_output(RandomText)
    chain = prompt | structured_llm
    random_text = chain.invoke({})
    return random_text.random_text

# Utilize chatbot to generate random text
from langgraph.checkpoint.memory import MemorySaver
from langgraph.graph import START, MessagesState, StateGraph
from langchain_core.messages import HumanMessage, AIMessage

# define a new graph
workflow = StateGraph(state_schema=MessagesState)

# define the function that calls the model
def call_model(state:MessagesState):
    #print(f'State Messages: {state["messages"]}')
    response = llm_high.invoke(state['messages'])
    return {'messages': response}

# define the (single) node in the graph
workflow.add_edge(START, 'model')
workflow.add_node('model', call_model)

# add memory
memory = MemorySaver()
app = workflow.compile(checkpointer=memory)
config = {'configurable': {'thread_id': 'abc123'}}
query = (
    "Generate a random piece of text between 50 and 100 words. "
    "Do not repeat any previously generated text. "
    "Vary the style randomly—this could include journalistic, casual blog, business report, internet meme, or any other tone. "
    "Ensure the output feels unpredictable in both content and style."
    "Ensure the output doesn't make any sence and is not related to any specific topic."
)
def generate_random_text_with_mem_chatbot():
    input_messages = [HumanMessage(query)]
    output = app.invoke({'messages': input_messages}, config=config)
    return output["messages"][-1].content

